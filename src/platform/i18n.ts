const DICTS: Record<Lang, Dict> = { de, en };

/** Keys that come in a `.one` / `.other` pair. */
type PluralKey = 'lineup.human' | 'lineup.cpu' | 'over.after' | 'daily.targets' | 'daily.shots' | 'daily.days' | 'stats.rounds' | 'stats.players' | 'pause.oracleBets';

let current: Lang = 'de';

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  current = lang;
}

/** First visit: follow the browser's language, German for German speakers and English for everyone else. */
export function detectLang(): Lang {
  const nav = typeof navigator !== 'undefined' ? navigator.language : '';
  return nav.toLowerCase().startsWith('de') ? 'de' : 'en';
}

export function isLang(v: unknown): v is Lang {
  return v === 'de' || v === 'en';
}

export function t(key: Key, params?: Params): string {
  const text = DICTS[current][key];
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m));
}

